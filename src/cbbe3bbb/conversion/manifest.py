"""``manifest.json`` of the generated output mod: one record per conversion.

The manifest marks the folder as tool-owned. The tool refuses to write into
an existing folder that has no manifest. It also records everything needed to
audit or undo a conversion: the source files with their hashes, the generated
files with their hashes, the Outfit Studio version, the settings, the
reference and the validation summary.
"""
from __future__ import annotations

import json
import os
import tempfile
import time
from pathlib import Path
from typing import TYPE_CHECKING, Any

from .. import __version__

if TYPE_CHECKING:  # pragma: no cover
    from .engine import ConversionResult
    from .plan import ConversionPlan
    from .runtime import RuntimeInfo
    from .validate import ValidationReport

__all__ = ["Manifest", "MANIFEST_NAME"]

MANIFEST_NAME = "manifest.json"


class Manifest:
    def __init__(self, mod_dir: Path, data: dict[str, Any]):
        self.mod_dir = Path(mod_dir)
        self.data = data

    @classmethod
    def load(cls, mod_dir: Path) -> "Manifest":
        p = Path(mod_dir) / MANIFEST_NAME
        if p.is_file():
            data = json.loads(p.read_text(encoding="utf-8"))
            if data.get("tool") != "CBBE3BBBConverter":
                raise ValueError(f"{p} is not a CBBE3BBBConverter manifest")
        else:
            data = {"schema": 1, "tool": "CBBE3BBBConverter", "created": time.strftime("%Y-%m-%dT%H:%M:%S"),
                    "note": "Files in this mod were generated by CBBE3BBBConverter. Only files listed here belong to the tool.",
                    "conversions": []}
        return cls(mod_dir, data)

    @property
    def records(self) -> list[dict]:
        return self.data.setdefault("conversions", [])

    @property
    def direct_records(self) -> list[dict]:
        """0.4.1 Direct-NIF conversions (game meshes written at their own game path). Read-only view: the key is
        only added to the file when the first Direct-NIF conversion is committed."""
        return self.data.get("direct_conversions", [])

    def add_direct_record(self, rec: dict) -> dict:
        self.data.setdefault("direct_conversions", []).append(rec)
        return rec

    def owned_files(self) -> set[str]:
        out = set()
        for r in self.records:
            for f in r.get("generated_files", []):
                out.add(f["path"].lower())
        for r in self.direct_records:
            if r.get("generated", {}).get("path"):
                out.add(r["generated"]["path"].lower())
        return out

    def add_record(self, plan: "ConversionPlan", res: "ConversionResult", rt: "RuntimeInfo",
                   written: list[tuple[Path, str]], val: "ValidationReport") -> dict:
        rec = {
            "id": res.id,
            "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S"),
            "tool_version": __version__,
            "status": "SUCCESS",
            "source": {
                "mod": plan.source_mod,
                "project": plan.source_project,
                "osp": plan.source_osp_rel,
                "osp_path": plan.source_osp_path,
                "set_index": plan.source_set_index,
                "shapedata": plan.source_shapedata_rel,
                "files": [
                    {"role": sf.role, "path": sf.rel, "abs_path": sf.abs_path, "provider": sf.provider,
                     "size": sf.size, "sha256": res.source_hashes_before.get(sf.abs_path, "")}
                    for sf in plan.staged_files
                ],
            },
            "target": {
                "project": plan.output_project,
                "osp": "Tools/BodySlide/" + plan.output_osp_rel,
                "shapedata": f"Tools/BodySlide/ShapeData/{plan.output_shapedata_folder}/{plan.output_shapedata_file}",
                "game_output_path": plan.output_game_path,
                "game_output_file": plan.output_game_file,
                "gen_weights": plan.source_gen_weights,
            },
            "generated_files": [
                {"path": str(p.relative_to(self.mod_dir)).replace("\\", "/"), "sha256": h, "size": p.stat().st_size}
                for p, h in written
            ],
            "outfit_studio": {"version": rt.version, "path": rt.path, "headless": rt.headless_label},
            "settings": {
                "search_radius": plan.search_radius,
                "max_vertex_targets": plan.max_vertex_targets,
                "no_target_limit": plan.no_target_limit,
                "weight_mode": plan.weight_mode,
                "bone_list": plan.bone_list,
                "auto_copy_ref": False,
                "regions": plan.regions,
                "physics_bones": plan.physics_bones,
                "shapes": plan.shapes_to_process,
            },
            "reference": {
                "template": plan.reference_template,
                "osp": plan.reference_osp_rel,
                "set": plan.reference_set,
                "shape": plan.reference_shape,
                "source": plan.reference_source,
            },
            "automation_script": plan.script_name + ".xml",
            "conversion_mode": getattr(plan, "conversion_mode", "outfit_only"),
            "validation": {"passed": val.passed, "failed_checks": [c.name for c in val.failures()], "metrics": val.metrics},
            "workspace": res.workspace,
        }
        self.records.append(rec)
        return rec

    def record_acceptance(self, generated_project: str, state: str, note: str = "") -> dict:
        """Append an in-game acceptance result to the latest record of ``generated_project`` (history is kept)."""
        recs = [r for r in self.records if r.get("target", {}).get("project") == generated_project]
        if not recs:
            raise KeyError(f"no conversion of '{generated_project}' in the manifest")
        rec = recs[-1]
        acc = rec.setdefault("acceptance", {"state": "", "history": []})
        acc.setdefault("history", [])
        entry = {"state": state, "note": note, "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S"), "tool_version": __version__}
        acc["history"].append(entry)
        acc["state"] = state
        return rec

    def save(self) -> Path:
        self.mod_dir.mkdir(parents=True, exist_ok=True)
        p = self.mod_dir / MANIFEST_NAME
        fd, tmp = tempfile.mkstemp(dir=self.mod_dir, prefix=".manifest-", suffix=".tmp")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as fh:
                json.dump(self.data, fh, indent=1)
            os.replace(tmp, p)
        finally:
            if os.path.exists(tmp):
                os.unlink(tmp)
        return p
