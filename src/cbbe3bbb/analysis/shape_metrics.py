__all__ = ["MetricSettings", "analyze_shape", "shape_edges", "BODY_NAME_PATTERNS", "body_data_folder"]

WEIGHT_EPS = 0.01
REGION_THR = 0.10
EXIST_THR = 0.05
TIGHT_DISTANCE = 1.5

BODY_NAME_PATTERNS = re.compile(
    r"^(cbbe(-3bbb)?|cbbe\s*3bbb.*|basefemalebody.*|basemalebody.*|femalebody|malebody|twb.*body.*|twb\s*3bbb.*|"
    r"fg\s*body.*|fusion\s*girl.*|fusiongirl.*|bodytalk.*|bt\d?\s*body.*|body)$",
    re.I,
)

# A shape entry's own DataFolder (``<Shape DataFolder="…">``) says where BodySlide reads that shape's slider data.
# Bodies copied into a project from a body project carry the BODY project's folder ("CBBE", "CBBE Vanilla",
# "TWB Vanilla", "BodyTalk3", "CBBE;TWB 3BBB Body", "… Body References"), and that is evidence of a body. Outfit shapes
# carry one too, whenever their slider data lives in another OUTFIT project's folder: merged outfit projects
# ("3BBB TWB Leotard" → Leotard, Catsuit, Jumpsuit) and every project generated by this converter, whose shapes keep
# reading their morphs from the source project's folder ("CP5_DonEb14n bodysuit v1"). Until 0.5.0 ANY per-shape
# DataFolder counted as body evidence, so a large generated bodysuit (≥ 8000 vertices, ≥ 80 units tall) was taken for
# a body: no region metrics, "agreement n/a" and "project contains only a body/reference shape" (Phase 3.2, see
# RESEARCH.md §14). Only a folder that itself names a body/reference project counts now; geometry-based body
# detection (reference match, surface coincidence) is unchanged.
BODY_FOLDER_PATTERNS = re.compile(
    r"^(cbbe(\s+(vanilla|reduced|body|3bbb(\s+body)?))?|cbbe[\s-]*3bbb.*body.*|twb\s+vanilla|twb[\s-]*3bbb\s+body|"
    r"true\s+wasteland\s+body.*|bodytalk\d*.*|fusion\s*girl.*|fg\s*body.*|.*\bbody\b.*|.*\breferences?\b.*)$",
    re.I,
)


def body_data_folder(data_folder: str) -> bool:
    """True when a per-shape DataFolder (possibly ``a;b``) points at a body/reference project's ShapeData folder."""
    return any(BODY_FOLDER_PATTERNS.match(f.strip()) for f in (data_folder or "").split(";") if f.strip())


@dataclass
class MetricSettings:
    search_radius: float = 5.0
    max_vertex_targets: int = 4
    no_target_limit: bool = False
    region_weight_threshold: float = REGION_THR


def shape_edges(tris: np.ndarray) -> np.ndarray:
    if tris.size == 0:
        return np.zeros((0, 2), dtype=np.int64)
    e = np.concatenate([tris[:, [0, 1]], tris[:, [1, 2]], tris[:, [2, 0]]]).astype(np.int64)
    e.sort(axis=1)
    return np.unique(e, axis=0)


def weld_map(verts: np.ndarray, tol: float = 1e-3) -> np.ndarray:
    """Map each vertex to a representative of all vertices at the same position (UV seams)."""
    if verts.size == 0:
        return np.zeros(0, dtype=np.int64)
    q = np.round(verts / tol).astype(np.int64)
    _, inv = np.unique(q, axis=0, return_inverse=True)
    return inv.reshape(-1)


def _islands(mask: np.ndarray, edges: np.ndarray, weld: np.ndarray, min_frac: float = 0.01) -> int:
    """Connected islands of masked vertices, with seam duplicates welded together.

    Islands smaller than ``max(3, min_frac * masked)`` vertices are ignored.
    """
    idx = np.flatnonzero(mask)
    if idx.size == 0:
        return 0
    nw = int(weld.max()) + 1 if weld.size else 0
    wmask = np.zeros(nw, dtype=bool)
    wmask[weld[idx]] = True
    widx = np.flatnonzero(wmask)
    min_size = max(3, int(min_frac * widx.size))
    if edges.size == 0:
        return int(widx.size >= min_size)
    we = weld[edges]
    sel = wmask[we[:, 0]] & wmask[we[:, 1]] & (we[:, 0] != we[:, 1])
    e = we[sel]
    g = coo_matrix((np.ones(len(e)), (e[:, 0], e[:, 1])), shape=(nw, nw))
    _, labels = connected_components(g, directed=False)
    counts = np.bincount(labels[widx])
    return int((counts >= min_size).sum())


def _level_for_relevance(pred_vertices: int, ref_coverage: float, pred_fraction: float) -> Level:
    if pred_vertices >= 30 and ref_coverage >= 0.5:
        return Level.HIGH
    if pred_vertices >= 15 and (ref_coverage >= 0.2 or pred_fraction >= 0.2):
        return Level.MEDIUM
    if pred_vertices >= 5:
        return Level.LOW
    return Level.NONE


def _fit_level(footprint: int, within: float, median: float, p90: float, radius: float) -> Level:
    """How well the garment surface over a region sits on the reference.

    Scaled to the transfer's search radius: HIGH means practically every
    region vertex is inside the radius with a comfortable margin, so the
    nearest-neighbour transfer is unambiguous.
    """
    if footprint == 0:
        return Level.UNKNOWN
    if within >= 0.95 and median <= 0.5 * radius and p90 <= 0.6 * radius:
        return Level.HIGH
    if within >= 0.80 and median <= 0.6 * radius:
        return Level.MEDIUM
    return Level.LOW


def _match_body(kb: KnowledgeBase, shape: NifShape, verts: np.ndarray, trees: dict) -> str:
    n = shape.num_vertices
    for sig in kb.body_signatures:
        if sig.vertex_count != n or n == 0:
            continue
        tree = trees.get(sig.name)
        if tree is None:
            tree = trees[sig.name] = cKDTree(sig.vertices)
        sample = verts[:: max(1, n // 800)]
        d, _ = tree.query(sample, k=1)
        if float(np.median(d)) < 1.0:
            return sig.name
    return ""


def analyze_shape(
    shape: NifShape,
    entry: Optional[ShapeEntry],
    kb: KnowledgeBase,
    settings: MetricSettings,
    slider_count: int = 0,
    tree_cache: Optional[dict] = None,
) -> ShapeAnalysis:
    trees = tree_cache if tree_cache is not None else {}
    verts = shape.world_vertices()
    n = shape.num_vertices
    sa = ShapeAnalysis(
        name=shape.name,
        target=entry.target if entry else shape.name,
        block_type=shape.block_type,
        vertices=n,
        triangles=int(shape.triangles.shape[0]),
        skinned=bool(shape.skinned and shape.bones),
        bone_count=len(shape.bones),
        sliders=slider_count,
        warnings=list(shape.notes),
    )
    if n == 0:
        sa.warnings.append("shape has no vertex data")
        return sa

    # --- body detection -----------------------------------------------------
    body = _match_body(kb, shape, verts, trees)
    name_like_body = bool(BODY_NAME_PATTERNS.match(shape.name.strip())) or bool(entry and body_data_folder(entry.data_folder))
    extent = float(verts[:, 2].max() - verts[:, 2].min())
    if body:
        sa.is_body, sa.body_match = True, body
    elif name_like_body and n >= 8000 and extent >= 80.0:
        sa.is_body, sa.body_match = True, "body-like shape (name/size)"

    # --- bones / existing weights --------------------------------------------
    bones, w = shape.weight_matrix()
    counts = (w > WEIGHT_EPS).sum(axis=0) if bones else np.zeros(0)
    phys = kb.physics_bones
    for b, c in zip(bones, counts):
        if b in phys and c > 0:
            sa.physics_bones[b] = int(c)
        elif b in LEGACY_PHYSICS_BONES and c > 0:
            sa.legacy_physics_bones[b] = int(c)
    if kb.skeleton_bones:
        sa.custom_bones = sorted(b for b in bones if b not in kb.skeleton_bones and b not in phys and b not in LEGACY_PHYSICS_BONES)
    if sa.skinned:
        tot = w.sum(axis=1)
        sa.unweighted_fraction = float((tot < 0.5).mean())
        if sa.unweighted_fraction > 0.05:
            sa.warnings.append(f"{sa.unweighted_fraction:.0%} of vertices are (nearly) unweighted")
    elif shape.bones == [] and not shape.skinned:
        sa.warnings.append("shape is not skinned")

    ref = kb.reference
    if ref is None or sa.is_body:
        return sa

    # --- distance to the reference ------------------------------------------
    r = settings.search_radius
    d_near, i_near = ref.nearest(verts)
    # A shape that coincides with the reference surface is (part of) a body,
    # e.g. a zapped/partial CBBE body or an older CBBE topology.
    if n >= 2000 and float(np.median(d_near)) < 0.1 and float((d_near <= 0.3).mean()) >= 0.9:
        sa.is_body, sa.body_match = True, "body-like shape (coincides with the reference surface)"
        return sa
    sa.distance = DistanceStats(
        median=round(float(np.median(d_near)), 3),
        p90=round(float(np.percentile(d_near, 90)), 3),
        max=round(float(d_near.max()), 3),
        frac_within_radius=round(float((d_near <= r).mean()), 4),
        frac_tight=round(float((d_near <= TIGHT_DISTANCE).mean()), 4),
    )

    pred = ref.predict_weights(verts, ref.physics_bones, r, settings.max_vertex_targets, settings.no_target_limit)
    col = {b: i for i, b in enumerate(ref.physics_bones)}
    out_tree = cKDTree(verts)
    edges = shape_edges(shape.triangles)
    weld = weld_map(verts)
    bone_idx = {b: i for i, b in enumerate(bones)}
    thr = settings.region_weight_threshold

    for region, rbones in ref.physics_regions.items():
        rm = RegionMetrics(region=region)
        pw = pred[:, [col[b] for b in rbones]].sum(axis=1) if rbones else np.zeros(n)
        rm.predicted_vertices = int((pw >= thr).sum())
        rm.predicted_fraction = round(rm.predicted_vertices / n, 4)
        rm.predicted_mass = round(float(pw.sum()), 2)
        rw = ref.region_weight(region)
        ref_region = rw >= thr
        if ref_region.any():
            dr, _ = out_tree.query(ref.vertices[ref_region], k=1, distance_upper_bound=r)
            rm.reference_coverage = round(float(np.isfinite(dr).mean()), 4)
        foot = rw[i_near] >= thr
        rm.footprint_vertices = int(foot.sum())
        if rm.footprint_vertices:
            fd = d_near[foot]
            rm.footprint_within_radius = round(float((fd <= r).mean()), 4)
            rm.footprint_median_distance = round(float(np.median(fd)), 3)
            rm.footprint_p90_distance = round(float(np.percentile(fd, 90)), 3)
        rm.fit = _fit_level(rm.footprint_vertices, rm.footprint_within_radius, rm.footprint_median_distance, rm.footprint_p90_distance, r).value
        rm.relevance = _level_for_relevance(rm.predicted_vertices, rm.reference_coverage, rm.predicted_fraction).value

        # predicted L/R balance (vertex counts; topology dependent, used relative to existing weights)
        lp = [col[b] for b in rbones if bone_side(b) == "L"]
        rp = [col[b] for b in rbones if bone_side(b) == "R"]
        if lp and rp:
            lw_pred = pred[:, lp].sum(axis=1)
            rw_pred = pred[:, rp].sum(axis=1)
            lc = int((lw_pred >= EXIST_THR).sum())
            rc = int((rw_pred >= EXIST_THR).sum())
            rm.predicted_lr_balance = round(min(lc, rc) / max(lc, rc), 3) if max(lc, rc) else None
            # topology independent: how much of each side of the reference region is covered
            for side, cols_side in (("L", [b for b in rbones if bone_side(b) == "L"]), ("R", [b for b in rbones if bone_side(b) == "R"])):
                sw = ref.weights[:, ref.bone_indices(cols_side)].sum(axis=1)
                mask_side = sw >= thr
                if mask_side.any():
                    ds, _ = out_tree.query(ref.vertices[mask_side], k=1, distance_upper_bound=r)
                    rm.side_coverage[side] = round(float(np.isfinite(ds).mean()), 4)
            cross = 0
            tot = 0
            for side, arr in (("L", lw_pred), ("R", rw_pred)):
                sign = ref.side_sign.get(side)
                if sign is None:
                    continue
                m = arr >= EXIST_THR
                tot += int(m.sum())
                cross += int((m & (verts[:, 0] * sign < -1.0)).sum())
            rm.predicted_cross_side_fraction = round(cross / tot, 4) if tot else None

        # existing 3BBB weighting of this region
        ex_cols = [bone_idx[b] for b in rbones if b in bone_idx]
        for b in rbones:
            if b in sa.physics_bones:
                rm.existing_bones[b] = sa.physics_bones[b]
        for b, c in sa.legacy_physics_bones.items():
            if LEGACY_PHYSICS_BONES[b].value == region:
                rm.legacy_bones[b] = c
        if ex_cols:
            ex = w[:, ex_cols].sum(axis=1)
            has = ex >= EXIST_THR
            rm.existing_vertices = int(has.sum())
            rm.existing_fraction = round(rm.existing_vertices / n, 4)
            if rm.existing_vertices:
                rel = has | (pw >= EXIST_THR)
                rm.agreement = round(1.0 - float(np.abs(ex[rel] - pw[rel]).mean()), 3)
                rm.outside_region_fraction = round(float((pw[has] < WEIGHT_EPS).mean()), 4)
                le = [bone_idx[b] for b in rbones if b in bone_idx and bone_side(b) == "L"]
                re_ = [bone_idx[b] for b in rbones if b in bone_idx and bone_side(b) == "R"]
                lw = w[:, le].sum(axis=1) if le else np.zeros(n)
                rwt = w[:, re_].sum(axis=1) if re_ else np.zeros(n)
                lc, rc = int((lw >= EXIST_THR).sum()), int((rwt >= EXIST_THR).sum())
                if lp and rp:
                    rm.lr_balance = round(min(lc, rc) / max(lc, rc), 3) if max(lc, rc) else None
                cross = 0
                sides = 0
                for sgn_key, arr in (("L", lw), ("R", rwt)):
                    sign = ref.side_sign.get(sgn_key)
                    if sign is None:
                        continue
                    m = arr >= EXIST_THR
                    sides += int(m.sum())
                    cross += int((m & (verts[:, 0] * sign < -1.0)).sum())
                rm.cross_side_fraction = round(cross / sides, 4) if sides else None
                rm.weight_islands = _islands(has, edges, weld)
                rm.predicted_weight_islands = _islands(pw >= EXIST_THR, edges, weld)
                if edges.size:
                    touch = has[edges[:, 0]] | has[edges[:, 1]]
                    if touch.any():
                        de = np.abs(ex[edges[touch, 0]] - ex[edges[touch, 1]])
                        rm.abrupt_edge_fraction = round(float((de > 0.5).mean()), 4)
        sa.regions[region] = rm
    return sa
